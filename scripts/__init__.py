"""Development and operations entry points."""

# [이 폴더를 공부하는 방법]
# scripts는 초기 설정, 테스트, 모델 설치, 빌드, 백업을 실행하는 보조 도구 모음이다.
# 실제 자비스 기능은 app 패키지에 있고, 이곳의 스크립트가 필요한 함수를 가져다 쓴다.
# __init__.py는 이 디렉터리를 일반 파이썬 패키지로 인식시키는 파일이다.
# 따라서 `from scripts import bootstrap`처럼 다른 파일에서 가져올 수 있다.
# 이 파일에는 설명만 있으므로 import 자체로 초기화나 백업 작업을 실행하지 않는다.
#
# 추천 학습 순서와 각 파일에서 배울 내용:
# 1. bootstrap.py   : 변수, 함수, 조건문, 반복문, Path, dataclass, 예외 처리
# 2. gate.py        : 외부 프로그램 실행, 문자열 처리, 딕셔너리, JSON 저장
# 3. setup_voice.py : 파일 분할 읽기, 다운로드, 해시 검증, 압축 파일 처리
# 4. build_exe.py   : 긴 문자열에 다른 언어 코드를 넣고 컴파일러에 전달하기
# 5. backup.py      : bytes, SQLite, 압축, 암호화 데이터 구성, 복원 검증
#
# 파일을 읽을 때는 맨 아래의 `if __name__ == "__main__":`부터 찾아보자.
# 보통 main() → 입력값 해석 → 실제 작업 함수 → 결과 출력 순서로 연결된다.
# `#` 뒤의 내용은 주석이며 실행되지 않는다. 반면 맨 위의 삼중 따옴표 문자열은
# 모듈 설명문(docstring)으로, 파이썬의 help() 등에서 읽을 수 있는 정보다.
# 함수의 `이름: 타입`과 `-> 타입`은 타입 힌트다. 그 자체가 값을 검사하지는 않는다.
